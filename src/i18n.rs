//! Small compile-time desktop localization catalog.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Language {
    English,
    SimplifiedChinese,
    TraditionalChinese,
}

impl Language {
    pub const ALL: [Self; 3] = [
        Self::English,
        Self::SimplifiedChinese,
        Self::TraditionalChinese,
    ];

    pub fn detect() -> Self {
        let locale = sys_locale::get_locale()
            .unwrap_or_default()
            .to_ascii_lowercase()
            .replace('_', "-");
        if locale.starts_with("zh-hant")
            || locale.starts_with("zh-tw")
            || locale.starts_with("zh-hk")
            || locale.starts_with("zh-mo")
        {
            Self::TraditionalChinese
        } else if locale.starts_with("zh") {
            Self::SimplifiedChinese
        } else {
            Self::English
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::SimplifiedChinese => "简体中文",
            Self::TraditionalChinese => "繁體中文",
        }
    }
}

impl Default for Language {
    fn default() -> Self {
        Self::detect()
    }
}

pub fn text(language: Language, key: &str) -> &'static str {
    match language {
        Language::English => english(key),
        Language::SimplifiedChinese => simplified_chinese(key),
        Language::TraditionalChinese => traditional_chinese(key),
    }
}

